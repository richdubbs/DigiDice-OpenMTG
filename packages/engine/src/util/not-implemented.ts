/**
 * The body of every stub the skeleton (milestone 5, WP0) leaves for a later work package: `throw new Error('not implemented: WPn')`.
 * A stub that is called is a loud failure, never a silent wrong answer. Capability tables of stubs are empty, so no card is ever classified
 * as automated by a stub (design 5.2).
 */
export function notImplemented(wp: string): never {
  throw new Error(`not implemented: ${wp}`);
}
