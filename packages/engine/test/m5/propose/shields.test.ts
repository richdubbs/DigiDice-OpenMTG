/**
 * WP11: shields (design 8.5): regeneration shields (CR 614.8, 701.19, transition T1: typed records that rules/destroy.ts reads) and prevention shields
 * (CR 615.7 "the next N damage", 615.8 "the next time", "all combat damage this turn"), a permanent's own prevention ability, unpreventable damage (CR 615.12)
 * and CR 614.7a. Combat damage and state-based destruction go through the same pipeline (the funnels of rules/damage.ts and rules/destroy.ts).
 */
import { describe, expect, it } from 'vitest';
import type { GameState, ReplacementDef } from '../../../src/index';
import { addRegenerationShield, destroy } from '../../../src/rules/destroy';
import { dealDamage } from '../../../src/rules/damage';
import { propose } from '../../../src/effects/propose';
import { find, inGraveyard, logHas, onBattlefield, runCombat, scenario, tweak } from '../helpers';
import { eventsOf, permanent, run, shieldRecord, staticAbility } from './support';

const board = (): GameState => scenario(['Hill Giant', 'Grizzly Bears', 'Craw Wurm'], { p1: { battlefield: ['Craw Wurm', 'Grizzly Bears'] }, p2: { battlefield: ['Hill Giant'] } });
const giantOf = (s: GameState): string => find(s, 'Hill Giant', 'battlefield');
const shielded = (s: GameState): GameState => run(s, (g) => addRegenerationShield(g, giantOf(s))).g.s;

describe('CR 701.19, 614.8: regeneration shields (transition T1: typed records)', () => {
  it('the shield is a typed replacement effect of "would be destroyed" for that permanent, until end of turn', () => {
    const s = shielded(board());
    expect(s.continuousEffects).toMatchObject([{
      duration: { d: 'endOfTurn' }, usesLeft: 1,
      effect: { s: 'replace', replaces: { ev: 'action', verb: 'destroy', object: { is: { ref: 'fixed', objects: [{ id: giantOf(s), zone: 'battlefield' }] } } }, body: { b: 'regeneration' }, shield: { uses: 1 } },
    }]);
  });

  it('design 8.5 trace (Wrath of God vs a shield): a destroy proposal that may be regenerated uses the shield: damage removed, tapped, out of combat, no zone change', () => {
    const s0 = tweak(shielded(board()), (t) => { t.objects[giantOf(t)]!.damage = 2; });
    const giant = giantOf(s0);
    const r = run(s0, (g) => propose(g, { ev: 'destroy', object: { id: giant, zone: 'battlefield' }, canRegenerate: true }));
    expect(r.g.s.objects[giant]).toMatchObject({ zone: 'battlefield', damage: 0, tapped: true });
    expect(eventsOf(r.g, 'zoneChanged')).toEqual([]);
    expect(r.g.s.continuousEffects).toEqual([]); // the shield is used up (CR 701.19a: "the next time")
  });

  it('CR 701.19c: "can\'t be regenerated" (Wrath of God): each creature is its own proposal with canRegenerate false; the shield does not apply', () => {
    const s0 = shielded(board());
    const ids = s0.zones.battlefield.filter((id) => s0.objects[id]!.defId !== 'Plains');
    const r = run(s0, (g) => ids.map((id) => propose(g, { ev: 'destroy', object: { id, zone: 'battlefield' }, canRegenerate: false })));
    expect(r.result).toEqual(ids.map(() => true));
    for (const name of ['Hill Giant', 'Grizzly Bears', 'Craw Wurm']) expect(onBattlefield(r.g.s, name)).toBe(false);
    expect(inGraveyard(r.g.s, 'Hill Giant', 'p2')).toBe(true);
    expect(r.g.s.continuousEffects).toHaveLength(1); // the unused shield stays until the cleanup step
  });

  it('a state-based destruction (lethal damage, CR 704.5g) is regenerated by the same shield (destroy owns regeneration for every route)', () => {
    const s0 = shielded(board());
    const r = run(s0, (g) => destroy(g, giantOf(s0), { reason: 'lethal damage', rules: ['CR 704.5g'] }));
    expect(r.result).toBe('regenerated');
    expect(logHas(r.g.s, /Hill Giant regenerates instead of being destroyed/, 'CR 701.19a')).toBe(true);
  });

  it('a shield for one permanent does not cover another (the fixed set, CR 611.2c), nor the same card as a new object (CR 400.7)', () => {
    const s0 = shielded(board());
    const bears = find(s0, 'Grizzly Bears', 'battlefield');
    expect(run(s0, (g) => destroy(g, bears)).result).toBe('destroyed');
    const moved = tweak(s0, (t) => { t.continuousEffects = t.continuousEffects.map((e) => ({ ...e, effect: JSON.parse(JSON.stringify(e.effect).replace('"battlefield"', '"graveyard"')) })); });
    expect(run(moved, (g) => destroy(g, giantOf(moved))).result).toBe('destroyed');
  });
});

const prevent = (amount: number | 'all', replaces: ReplacementDef['replaces'], uses: number | 'all' = 1): ReplacementDef => ({ s: 'replace', replaces, body: { b: 'prevent', amount }, shield: { uses } });
const toObject = (id: string): ReplacementDef['replaces'] => ({ ev: 'damage', recipient: { object: { is: { ref: 'fixed', objects: [{ id, zone: 'battlefield' }] } } } });

describe('CR 615: prevention shields', () => {
  it('CR 615.7: "prevent the next 3 damage": 2 then 2 deals 0 then 1; the shield counts down and is gone when spent', () => {
    const s0 = board();
    const [wurm, giant] = [find(s0, 'Craw Wurm', 'battlefield'), giantOf(s0)];
    const s1 = tweak(s0, (t) => { t.continuousEffects.push(shieldRecord('e90', prevent(3, toObject(giant), 'all'))); });
    const first = run(s1, (g) => dealDamage(g, wurm, giant, 2));
    expect(first.result).toBe(0);
    expect(first.g.s.objects[giant]!.damage).toBe(0);
    expect(eventsOf(first.g, 'damageDealt')).toEqual([]); // CR 615.6, 614.7a: prevented damage is never dealt and triggers nothing
    expect(first.g.s.continuousEffects[0]!).toMatchObject({ usesLeft: 1 });
    const second = run(first.g.s, (g) => dealDamage(g, wurm, giant, 2));
    expect(second.result).toBe(1);
    expect(second.g.s.objects[giant]!.damage).toBe(1);
    expect(second.g.s.continuousEffects).toEqual([]);
    expect(logHas(second.g.s, /1 damage Craw Wurm would deal to Hill Giant is prevented/, 'CR 615.7')).toBe(true);
  });

  it('CR 615.8: "the next time a source would deal damage" prevents one whole instance, then the shield is gone', () => {
    const s0 = board();
    const [wurm, giant] = [find(s0, 'Craw Wurm', 'battlefield'), giantOf(s0)];
    const s1 = tweak(s0, (t) => { t.continuousEffects.push(shieldRecord('e90', prevent('all', { ev: 'damage', source: { is: { ref: 'fixed', objects: [{ id: wurm, zone: 'battlefield' }] } } }))); });
    const r = run(s1, (g) => [dealDamage(g, wurm, giant, 6), dealDamage(g, wurm, giant, 2)]);
    expect(r.result).toEqual([0, 2]);
  });

  it('Fog ("prevent all combat damage that would be dealt this turn"): combat damage is prevented, other damage is not', () => {
    const s0 = board();
    const [wurm, giant] = [find(s0, 'Craw Wurm', 'battlefield'), giantOf(s0)];
    const fogged = tweak(s0, (t) => { t.continuousEffects.push(shieldRecord('e90', prevent('all', { ev: 'damage', combat: true }, 'all'), { sourceName: 'Fog' })); });
    const after = runCombat(fogged, { attack: [[wurm]], block: [[giant, wurm]] });
    expect(after.objects[giant]?.damage).toBe(0);
    expect(after.objects[wurm]?.damage).toBe(0);
    expect(onBattlefield(after, 'Hill Giant')).toBe(true);
    expect(run(fogged, (g) => dealDamage(g, wurm, giant, 3)).result).toBe(3);
  });

  it('CR 615.12: damage that can\'t be prevented is dealt, and the shield is not reduced', () => {
    const s0 = board();
    const [wurm, giant] = [find(s0, 'Craw Wurm', 'battlefield'), giantOf(s0)];
    const s1 = tweak(s0, (t) => { t.continuousEffects.push(shieldRecord('e90', prevent(3, toObject(giant), 'all'))); });
    const r = run(s1, (g) => propose(g, { ev: 'damage', source: { id: wurm, zone: 'battlefield' }, to: { id: giant, zone: 'battlefield' }, amount: 2, combat: false, unpreventable: true }));
    expect(r.g.s.objects[giant]!.damage).toBe(2);
    expect(r.g.s.continuousEffects[0]!).not.toHaveProperty('usesLeft');
  });

  it('CR 616.1: two shields on the same damage: the affected object\'s controller chooses which applies first', () => {
    const s0 = board();
    const [wurm, giant] = [find(s0, 'Craw Wurm', 'battlefield'), giantOf(s0)];
    const s1 = tweak(s0, (t) => {
      t.continuousEffects.push(shieldRecord('e90', prevent(1, toObject(giant), 'all'), { sourceName: 'Small' }), shieldRecord('e91', prevent(5, toObject(giant), 'all'), { sourceName: 'Big' }));
    });
    const asked = run(s1, (g) => dealDamage(g, wurm, giant, 3));
    expect(asked.need).toMatchObject({ kind: 'chooseReplacement', player: 'p2', options: [{ id: 'shield:e90' }, { id: 'shield:e91' }] });
    const r = run(s1, (g) => dealDamage(g, wurm, giant, 3), [{ kind: 'chooseReplacement', id: 'shield:e91' }]);
    expect(r.result).toBe(0); // the big shield took all 3 (CR 614.5: it is not applied again); the small one is untouched
    expect(r.g.s.continuousEffects.map((e) => [e.id, (e as { usesLeft?: number }).usesLeft])).toEqual([['e90', undefined], ['e91', 2]]);
  });

  it('a permanent\'s own "prevent all damage that would be dealt to ~" (feature:replace.self) applies to combat damage too; the damage it deals is not prevented', () => {
    const wall = permanent('Test Ward Wall', 'Creature — Wall', [
      staticAbility('Prevent all damage that would be dealt to ~.', [{ s: 'replace', replaces: { ev: 'damage', recipient: { object: { self: true } } }, body: { b: 'prevent', amount: 'all' } }]),
    ], { pt: ['2', '2'] });
    const s0 = scenario(['Craw Wurm'], { p1: { battlefield: ['Craw Wurm'] }, p2: { battlefield: ['Test Ward Wall'] }, defs: [wall] });
    const [wurm, w] = [find(s0, 'Craw Wurm', 'battlefield'), find(s0, 'Test Ward Wall', 'battlefield')];
    const after = runCombat(s0, { attack: [[wurm]], block: [[w, wurm]] });
    expect(after.objects[w]?.damage).toBe(0);
    expect(after.objects[wurm]?.damage).toBe(2);
  });
});

describe('CR 614.7a: 0 damage is no event', () => {
  it('a proposal of 0 damage is not performed (no damageDealt event, nothing for a replacement to modify)', () => {
    const s0 = board();
    const r = run(s0, (g) => propose(g, { ev: 'damage', source: { id: find(s0, 'Craw Wurm', 'battlefield'), zone: 'battlefield' }, to: 'p2', amount: 0, combat: false, unpreventable: false }));
    expect(r.result).toBe(false);
    expect(r.g.events).toEqual([]);
  });

  it('damage prevented entirely is not performed either: propose answers false', () => {
    const s0 = board();
    const giant = giantOf(s0);
    const s1 = tweak(s0, (t) => { t.continuousEffects.push(shieldRecord('e90', prevent('all', toObject(giant)))); });
    const r = run(s1, (g) => propose(g, { ev: 'damage', source: { id: find(s1, 'Craw Wurm', 'battlefield'), zone: 'battlefield' }, to: { id: giant, zone: 'battlefield' }, amount: 4, combat: false, unpreventable: false }));
    expect(r.result).toBe(false);
    expect(eventsOf(r.g, 'damageDealt')).toEqual([]);
  });
});

