/**
 * Expansion snapshots and the type check of the keyword data (design 15.2 WP3: "expansion snapshots for sample parameters"; "expansion type-check").
 *
 *  - `expansions.snap.json` records, for every sample instance in samples.ts, the abilities its data expands into. A change to a data file or to expand.ts
 *    shows up in review as a diff of this file. (`actsThroughData` is false for flashback: its data is the spec of native engine code and the registry gives
 *    no abilities for it, so it can never act twice.)
 *  - `expansion-types.generated.ts` holds the same expansions as TypeScript object literals typed `AbilityDef[]`, so `npm run typecheck` checks every generated
 *    ability against the real model types (an unknown field, a wrong discriminator or a missing required field is a compile error). This test regenerates the
 *    text and fails when the committed file differs; run with UPDATE_KEYWORD_TYPES=1 to rewrite it. (WP1's `validateAbility` will check the same
 *    abilities against the JSON schema once it is merged.)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { expandKeyword } from '../../../src/keywords/expand';
import { keywordRegistry } from '../../../src/keywords/registry';
import type { ExpandContext } from '../../../src/keywords/types';
import { SAMPLES } from './samples';

const HERE = dirname(fileURLToPath(import.meta.url));
const ctx: ExpandContext = { granted: false, faceName: 'Test', types: ['Creature'], keyPrefix: 'k:0:0' };

/** The abilities of the DATA for a sample (not gated by status: the native keyword's data form is checked too). */
const dataExpansion = (label: string) => {
  const instance = SAMPLES[label]!;
  return expandKeyword(keywordRegistry.get(instance.keyword)!, instance, ctx);
};

describe('expansions of the keyword data for sample parameters', () => {
  it('snapshot: what each sample instance expands into (expansions.snap.json)', async () => {
    const snap = Object.fromEntries(
      Object.entries(SAMPLES).map(([label, instance]) => {
        const def = keywordRegistry.get(instance.keyword)!;
        return [label, { keyword: def.name, status: def.status, actsThroughData: def.status === 'implemented', abilities: dataExpansion(label) }];
      }),
    );
    await expect(`${JSON.stringify(snap, null, 2)}\n`).toMatchFileSnapshot('./expansions.snap.json');
  });

  it('every sample belongs to a keyword that has an expansion, and the registry agrees with the data for implemented ones', () => {
    for (const [label, instance] of Object.entries(SAMPLES)) {
      const def = keywordRegistry.get(instance.keyword)!;
      expect(def.expand, label).toBeDefined();
      if (def.status === 'implemented') expect(keywordRegistry.expand(instance, ctx), label).toEqual(dataExpansion(label));
      else expect(keywordRegistry.expand(instance, ctx), label).toEqual([]);
    }
  });

  it('the type-check file is up to date (a change to the data or to the samples needs UPDATE_KEYWORD_TYPES=1)', () => {
    const lines = [
      '// GENERATED by expansions.test.ts from keywords/data and samples.ts. Do not edit; run `UPDATE_KEYWORD_TYPES=1 npx vitest run packages/engine/test/m5/keywords/expansions.test.ts`.',
      '// Every keyword expansion as a typed literal: `npm run typecheck` checks it against the ability model (types/ability.ts).',
      "import type { AbilityDef } from '../../../src/types/ability';",
      '',
      'export const EXPANSIONS: Record<string, AbilityDef[]> = {',
    ];
    for (const label of Object.keys(SAMPLES)) lines.push(`  ${JSON.stringify(label)}: ${JSON.stringify(dataExpansion(label), null, 2).replace(/\n/g, '\n  ')},`);
    lines.push('};', '');
    const expected = lines.join('\n');
    const file = join(HERE, 'expansion-types.generated.ts');
    if (process.env['UPDATE_KEYWORD_TYPES'] === '1' || !existsSync(file)) writeFileSync(file, expected);
    expect(readFileSync(file, 'utf8')).toBe(expected);
  });
});
