#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md from installed node_modules and check that every
 * dependency uses a license compatible with MIT.
 *
 *   node scripts/third-party-notices.mjs          # write THIRD_PARTY_NOTICES.md
 *   node scripts/third-party-notices.mjs --check  # exit 1 if a disallowed/unknown license is found
 */
import { readFileSync, readdirSync, existsSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'CC0-1.0', 'Unlicense',
  'BlueOak-1.0.0', 'CC-BY-4.0', 'Python-2.0', 'Zlib',
  // permissive, no conditions (truncate-utf8-bytes, under the desktop installer's electron-builder; build time only, never bundled)
  'WTFPL',
]);

/** Evaluate a simple SPDX expression: OR = any allowed, AND = all allowed. */
function licenseAllowed(expr) {
  if (!expr) return false;
  const e = expr.replace(/[()]/g, ' ').trim();
  if (/\sOR\s/i.test(e)) return e.split(/\sOR\s/i).some((x) => licenseAllowed(x.trim()));
  if (/\sAND\s/i.test(e)) return e.split(/\sAND\s/i).every((x) => licenseAllowed(x.trim()));
  return ALLOWED.has(e);
}

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return '';
}

function repoOf(pkg) {
  const r = pkg.repository;
  if (!r) return pkg.homepage ?? '';
  const url = typeof r === 'string' ? r : r.url ?? '';
  return url.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://');
}

const found = new Map();
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const p = join(dir, name);
    if (!statSync(p).isDirectory()) continue;
    if (name.startsWith('@')) { walk(p); continue; }
    const pj = join(p, 'package.json');
    if (existsSync(pj)) {
      try {
        const pkg = JSON.parse(readFileSync(pj, 'utf8'));
        if (pkg.name && pkg.version && !pkg.name.startsWith('@openmtg/')) {
          const key = `${pkg.name}@${pkg.version}`;
          if (!found.has(key)) {
            const licFile = readdirSync(p).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
            found.set(key, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), repo: repoOf(pkg), licenseFile: licFile ? join(p, licFile) : null });
          }
        }
      } catch { /* ignore unreadable package.json */ }
    }
    walk(join(p, 'node_modules'));
  }
}
walk(join(root, 'node_modules'));
for (const pkgDir of existsSync(join(root, 'packages')) ? readdirSync(join(root, 'packages')) : []) walk(join(root, 'packages', pkgDir, 'node_modules'));

const rows = [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const bad = rows.filter((r) => !licenseAllowed(r.license));

if (process.argv.includes('--check')) {
  if (bad.length) {
    console.error('Dependencies with disallowed or unknown licenses:');
    for (const r of bad) console.error(`  ${r.name}@${r.version}: ${r.license || '(none)'}`);
    process.exit(1);
  }
  console.log(`License check passed for ${rows.length} packages.`);
  process.exit(0);
}

const lines = [
  '# Third-party notices',
  '',
  'OpenMTG\'s own code is MIT licensed (see LICENSE). This file lists the third-party npm packages',
  'installed for development and/or bundled into the browser client, with their licenses.',
  'Generated by `npm run notices`; do not edit by hand.',
  '',
  'Card data and images are not bundled: they are fetched from Scryfall at runtime by the user\'s',
  'machine and are property of their respective owners (see README).',
  '',
  `Packages: ${rows.length}. Disallowed or unknown licenses: ${bad.length}.`,
  '',
  '| Package | Version | License | Source |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license || 'UNKNOWN'} | ${r.repo} |`),
  '',
  '## License texts',
  '',
];
const seenText = new Set();
for (const r of rows) {
  if (!r.licenseFile) continue;
  const text = readFileSync(r.licenseFile, 'utf8').trim();
  const key = `${r.name}\n${text}`;
  if (seenText.has(key)) continue;
  seenText.add(key);
  lines.push(`### ${r.name}@${r.version} (${r.license || 'UNKNOWN'})`, '', '```text', text.replace(/```/g, "'''"), '```', '');
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages, ${bad.length} flagged).`);
if (bad.length) for (const r of bad) console.warn(`  FLAGGED ${r.name}@${r.version}: ${r.license || '(none)'}`);
